# リストア訓練が本番に残す鼓動
#
# 業務データだけを本番と復元側で突き合わせると、売上が 1 件も入らない日は
# 両者が自明に一致し、判定が integrity_check だけに退化する。出張販売は
# 毎日あるとは限らないため、その静止期間はときに数日から数週間に及ぶ。
# その間レプリケーションが死んでいても緑が返り続ける。
#
# 訓練自身が毎回 1 行書けば、比べる対象が業務のリズムから独立する。
# 店が休みでも鼓動は増えるので、複製が止まればその翌日には食い違う。
class BackupHeartbeat < ApplicationRecord
  def self.beat!
    create!
  end
end
